function getSafeStoredLocale(): SupportedLocale {
  try {
    const saved = localStorage.getItem('eidos_locale');
    if (saved && isSupportedLocale(saved)) {
      return saved.toLowerCase() as SupportedLocale;
    }
    // Ensure default authority is strictly Turkish ('tr')
    localStorage.setItem('eidos_locale', 'tr');
  } catch {
    // Ignore storage errors in restricted contexts
  }
  return 'tr';
}

function setSafeStoredLocale(lang: SupportedLocale): void {
  try {
    localStorage.setItem('eidos_locale', lang);
  } catch {
    // Ignore storage quota errors
  }
}

const DictionaryContext = createContext<DictionaryContextType | null>(null);

function deepMergeDict(fallback: DictionaryBundle, remote: Partial<DictionaryBundle>): DictionaryBundle {
  function mergeObjects(base: any, override: any): any {
    if (!override || typeof override !== 'object' || Array.isArray(override)) {
      return override !== undefined ? override : base;
    }
    const result: any = { ...base };
    for (const key of Object.keys(override)) {
      const oVal = override[key];
      const bVal = base ? base[key] : undefined;
      if (oVal && typeof oVal === 'object' && !Array.isArray(oVal) && bVal && typeof bVal === 'object' && !Array.isArray(bVal)) {
        result[key] = mergeObjects(bVal, oVal);
      } else if (oVal !== undefined) {
        result[key] = oVal;
      }
    }
    return result;
  }
  return mergeObjects(fallback, remote) as DictionaryBundle;
}

export function getCachedDictionary(locale: SupportedLocale = getSafeStoredLocale()): DictionaryBundle {
  try {
    const raw = localStorage.getItem(`eidos_dict_${locale}`);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && typeof parsed === 'object') {
        return deepMergeDict(initialFallbackDict, parsed);
      }
    }
  } catch {
    // Ignore parse or storage errors in restricted web contexts
  }
  return initialFallbackDict;
}

export const DictionaryProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const initialLocale = getSafeStoredLocale();
  const [locale, setLocaleState] = useState<SupportedLocale>(initialLocale);
  const [dict, setDict] = useState<DictionaryBundle>(() => getCachedDictionary(initialLocale));
  const [remoteConfig, setRemoteConfig] = useState<RemoteConfig>(initialRemoteConfig);
  const [isLoading, setIsLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  const abortControllerRef = useRef<AbortController | null>(null);

  const fetchDictionary = useCallback(async (lang: SupportedLocale, userInitiated = false) => {
    // Abort previous in-flight request to prevent race conditions
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
    }
    const controller = new AbortController();
    abortControllerRef.current = controller;

    setIsLoading(true);
    setError(null);

    try {
      const res = await apiRequest<{
        locale: SupportedLocale;
        dictionary: DictionaryBundle;
        remoteConfig: RemoteConfig;
      }>(`/api/v1/config/dictionary?lang=${lang}`, {
        signal: controller.signal,
      });

      if (res && res.dictionary) {
        // Deep merge with fallback to ensure any newly added sections never become undefined
        const merged = deepMergeDict(initialFallbackDict, res.dictionary);
        setDict(merged);
        if (res.remoteConfig) setRemoteConfig(res.remoteConfig);

        // Cache for instant local offline retrieval
        try {
          localStorage.setItem(`eidos_dict_${lang}`, JSON.stringify(res.dictionary));
        } catch {
          // Ignore quota errors
        }

        if (userInitiated) {
          toast.success(merged.settings?.languageSwitchedToast || 'Arayüz dili güncellendi.');
        }
      }
    } catch (err: any) {
      if (err?.name === 'AbortError' || err?.code === 'ABORT_ERR') return;
      console.warn('[DICTIONARY_FETCH_WARN] Using fallback dictionary bundle:', err);
      const statusCode = typeof err?.statusCode === 'number' ? err.statusCode : undefined;
      const statusLabel = statusCode ? `HTTP ${statusCode}` : 'Ağ / Çevrimdışı';
      const errMsg = err?.message || 'Uzak sözlük paketi yüklenemedi.';
      setError(errMsg);
      toast.error(`${errMsg} (${statusLabel})`, {
        description: 'Uzak sunucu yanıt vermedi. Güvenli yerel sözlük paketi devrede.',
        duration: 4500,
      });
    } finally {
      setIsLoading(false);
    }
  }, []);

  const setLocale = useCallback(
    (lang: SupportedLocale) => {
      if (lang === locale && !isLoading) return;
      setLocaleState(lang);
      setSafeStoredLocale(lang);
      // Immediately switch to cached bundle for instant zero-latency UI transition
      const cached = getCachedDictionary(lang);
      setDict(cached);
      fetchDictionary(lang, true);
    },
    [fetchDictionary, locale, isLoading]
  );

  useEffect(() => {
    fetchDictionary(locale, false);
    return () => {
      if (abortControllerRef.current) {
        abortControllerRef.current.abort();
      }
    };
  }, [fetchDictionary, locale]);

  const t = useCallback(
    (template: string, params?: Record<string, string | number | undefined | null>): string => {
      return interpolate(template, params);
    },
    []
  );

  return (
    <DictionaryContext.Provider
      value={{
        locale,
        availableLocales: supportedLocalesList,
        dict,
        remoteConfig,
        isLoading,
        error,
        setLocale,
        refreshDictionary: () => fetchDictionary(locale, false),
        t,
      }}
    >
      {children}
    </DictionaryContext.Provider>
  );
};

export function useDictionary(): DictionaryContextType {
  const context = useContext(DictionaryContext);
  if (!context) {
    throw new Error('useDictionary must be used within a DictionaryProvider');
  }
  return context;
}
