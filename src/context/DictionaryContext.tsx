function getSafeStoredLocale(): SupportedLocale {
  try {
    const saved = localStorage.getItem('eidos_locale');
    if (saved && isSupportedLocale(saved)) {
      return saved.toLowerCase() as SupportedLocale;
    }
    // Ensure default authority is strictly Turkish ('tr')
    localStorage.setItem('eidos_locale', 'tr');
  } catch {
    // Ignore storage errors in restricted contexts
  }
  return 'tr';
}

function setSafeStoredLocale(lang: SupportedLocale): void {
  try {
    localStorage.setItem('eidos_locale', lang);
  } catch {
    // Ignore storage quota errors
  }
}

const DictionaryContext = createContext<DictionaryContextType | null>(null);

function deepMergeDict(fallback: DictionaryBundle, remote: Partial<DictionaryBundle>): DictionaryBundle {
  const result: any = { ...fallback };
  for (const key of Object.keys(remote)) {
    const rVal = (remote as any)[key];
    const fVal = (fallback as any)[key];
    if (rVal && typeof rVal === 'object' && !Array.isArray(rVal) && fVal && typeof fVal === 'object') {
      result[key] = { ...fVal, ...rVal };
    } else if (rVal !== undefined) {
      result[key] = rVal;
    }
  }
  return result as DictionaryBundle;
}

export const DictionaryProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<SupportedLocale>(getSafeStoredLocale);
  const [dict, setDict] = useState<DictionaryBundle>(initialFallbackDict);
  const [remoteConfig, setRemoteConfig] = useState<RemoteConfig>(initialRemoteConfig);
  const [isLoading, setIsLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);

  const abortControllerRef = useRef<AbortController | null>(null);

  const fetchDictionary = useCallback(async (lang: SupportedLocale) => {
    // Abort previous in-flight request to prevent race conditions
    if (abortControllerRef.current) {
      abortControllerRef.current.abort();
    }
    const controller = new AbortController();
    abortControllerRef.current = controller;

    setIsLoading(true);
    setError(null);

    try {
      const res = await apiRequest<{
        locale: SupportedLocale;
        dictionary: DictionaryBundle;
        remoteConfig: RemoteConfig;
      }>(`/api/v1/config/dictionary?lang=${lang}`, {
        signal: controller.signal,
      });

      if (res && res.dictionary) {
        // Deep merge with fallback to ensure any newly added sections (like dialogueStudy) never become undefined
        const merged = deepMergeDict(initialFallbackDict, res.dictionary);
        setDict(merged);
        if (res.remoteConfig) setRemoteConfig(res.remoteConfig);
      }
    } catch (err: any) {
      if (err.name === 'AbortError') return;
      console.warn('[DICTIONARY_FETCH_WARN] Using fallback dictionary bundle:', err);
      const errMsg = err?.message || 'Failed to load remote dictionary.';
      setError(errMsg);
      toast.error(errMsg, {
        description: `HTTP / Ağ Durumu: ${err?.statusCode || 'Offline'}`,
        duration: 4000,
      });
    } finally {
      setIsLoading(false);
    }
  }, []);

  const setLocale = useCallback(
    (lang: SupportedLocale) => {
      setLocaleState(lang);
      setSafeStoredLocale(lang);
      fetchDictionary(lang);
    },
    [fetchDictionary]
  );

  useEffect(() => {
    fetchDictionary(locale);
    return () => {
      if (abortControllerRef.current) {
        abortControllerRef.current.abort();
      }
    };
  }, [fetchDictionary, locale]);

  return (
    <DictionaryContext.Provider
      value={{
        locale,
        availableLocales: supportedLocalesList,
        dict,
        remoteConfig,
        isLoading,
        error,
        setLocale,
        refreshDictionary: () => fetchDictionary(locale),
      }}
    >
      {children}
    </DictionaryContext.Provider>
  );
};

export function useDictionary(): DictionaryContextType {
  const context = useContext(DictionaryContext);
  if (!context) {
    throw new Error('useDictionary must be used within a DictionaryProvider');
  }
  return context;
}
